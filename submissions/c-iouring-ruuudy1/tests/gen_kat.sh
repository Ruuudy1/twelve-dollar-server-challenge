#!/bin/bash
# Generates kat_sha256.h: SHA-256 and HMAC-SHA256 known answers from openssl (cross product from python hmac).
# Usage: bash gen_kat.sh > kat_sha256.h
set -euo pipefail
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
python3 - "$tmp" <<'PY'
import sys, hashlib, hmac
d = sys.argv[1]
def pat(n, mul, add): return bytes(((i * mul + add) & 255) for i in range(n))
for n in range(301):
    open(f"{d}/m{n}", "wb").write(pat(n, 131, 17))
for n in range(201):
    open(f"{d}/k{n}", "w").write(pat(n, 29, 5).hex())
cross = []
for k in range(201):
    key = pat(k, 29, 5)
    blob = b"".join(hmac.new(key, pat(m, 131, 17), hashlib.sha256).digest() for m in range(301))
    cross.append(hashlib.sha256(blob).hexdigest())
open(f"{d}/cross", "w").write("\n".join(cross) + "\n")
PY
emit() { # emit <name> <count> then hex lines on stdin
  echo "static const char *const $1[$2] = {"
  while read -r h; do echo "    \"$h\","; done
  echo "};"
}
hexof() { openssl dgst -sha256 -r | cut -d' ' -f1; }
mac() { if [ -z "$1" ]; then openssl dgst -sha256 -hmac "" -r | cut -d" " -f1; else openssl dgst -sha256 -mac HMAC -macopt "hexkey:$1" -r | cut -d" " -f1; fi; }
echo "// Generated by gen_kat.sh with openssl dgst and python hmac. Do not edit."
echo "// Message n has byte i = (i * 131 + 17) & 255; key n has byte i = (i * 29 + 5) & 255."
for n in $(seq 0 300); do hexof < "$tmp/m$n"; done | emit kat_sha256_len 301
for k in $(seq 0 200); do m=$(( (k * 37) % 301 )); mac "$(cat "$tmp/k$k")" < "$tmp/m$m"; done | emit kat_hmac_by_key 201
for n in $(seq 0 300); do mac "$(cat "$tmp/k20")" < "$tmp/m$n"; done | emit kat_hmac_key20 301
for n in $(seq 0 300); do mac "$(cat "$tmp/k65")" < "$tmp/m$n"; done | emit kat_hmac_key65 301
emit kat_hmac_cross 201 < "$tmp/cross"
