// Prints tests/json_expect.h: JSON.stringify output (without quotes) for every ASCII byte.
// Regenerate with: node tests/gen_json_expect.js > tests/json_expect.h
'use strict';
const BACKSLASH = String.fromCharCode(92);
function cLiteral(s) {
  let out = '"';
  for (const ch of s) {
    out += ch === BACKSLASH || ch === '"' ? BACKSLASH + ch : ch === String.fromCharCode(127) ? BACKSLASH + 'x7f' : ch;
  }
  return out + '"';
}
const rows = [];
for (let b = 0; b < 128; b++) {
  const q = JSON.stringify(String.fromCharCode(b));
  rows.push('    ' + cLiteral(q.slice(1, -1)) + ',');
}
process.stdout.write('// Generated by gen_json_expect.js from node JSON.stringify; do not edit by hand.\n');
process.stdout.write('#pragma once\n\n');
process.stdout.write('static const char *const json_expect_ascii[128] = {\n' + rows.join('\n') + '\n};\n');
